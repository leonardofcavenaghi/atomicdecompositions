"""GKM graph of a smooth projective toric variety and the genus-0
localization engine (Holmes-Muratore Theorem 3.4 = Liu-Sheshmani
Theorem 4.7, the same graph sum gwflags.gkm implements for flags).

Toric dictionary (fixed point p_sigma <-> maximal cone sigma):
  * flags at sigma  <-> rays rho_i in sigma; axial weight = dual-basis
    covector m_i (m_i(rho_j) = delta_ij);
  * edge of the flag  = invariant curve C_tau, tau = sigma \\ {rho_i};
  * connection integers of the flag (rho_i, sigma) along C_tau: for the
    other rays rho_j in tau the degree of O(D_{rho_j})|_{C_tau}, which is
    the wall coefficient b_{rho_j} of [C_tau] (N_{C_tau/X} = (+) O(D_rho)
    over rho in tau), and 2 for the curve itself;
  * equivariant lift of the divisor class x_i restricted to sigma is m_i
    if rho_i in sigma, 0 otherwise; products of classes restrict to
    products.

Compared with the flag engine, curve classes are kept as vectors in
Z^{Sigma(1)} (they can have negative entries), so the degree of an edge is
bounded by an ample divisor instead of by componentwise subtraction, and
several insertion tuples can be evaluated on one pass over the fixed loci
(gw_multi), which the quantum-multiplication block relies on.
"""

from fractions import Fraction
from functools import lru_cache

from gwflags.gkm import GKMGraph, GKMEngine
from gwflags.trees import all_possible_marks, ahu_canon
from .progress import ACTIVE_PROGRESS


class Cancelled(Exception):
    """Raised inside the graph sum when the cancel callback asks it to
    stop (the GUI's Stop button); no result is produced."""


# ------------------------------------------------------------ trees
def _rooted_level_sequences(n):
    """Beyer-Hedetniemi: level sequences of all rooted trees on n nodes."""
    L = list(range(n))
    yield list(L)
    while True:
        p = n - 1
        while p > 0 and L[p] == 1:
            p -= 1
        if p == 0:
            return
        q = p - 1
        while L[q] != L[p] - 1:
            q -= 1
        for i in range(p, n):
            L[i] = L[i - p + q]
        yield list(L)


@lru_cache(maxsize=None)
def free_trees(n):
    """All trees on vertices 1..n up to isomorphism, as (edges, n) with
    edges a tuple of (u, v), u < v.  Rooted trees are generated by level
    sequences and deduplicated by AHU canonical form."""
    if n == 1:
        return [((), 1)]
    seen, out = set(), []
    reporter = ACTIVE_PROGRESS.get()
    if reporter:
        reporter.emit(force=True, stage='generating_tree_shapes', generation_vertices=n,
                      rooted_shapes_examined=0, unique_shapes_generated=0)
    for generated, L in enumerate(_rooted_level_sequences(n), 1):
        if reporter and generated % 1024 == 0:
            reporter.emit(rooted_shapes_examined=generated, unique_shapes_generated=len(out))
        parent = {}
        stack = []
        for i, lev in enumerate(L):
            while len(stack) > lev:
                stack.pop()
            if stack:
                parent[i] = stack[-1]
            stack.append(i)
        edges = tuple(sorted(tuple(sorted((c + 1, p + 1)))
                             for c, p in parent.items()))
        adj = {v: [] for v in range(1, n + 1)}
        for e in edges:
            adj[e[0]].append((e[1], e))
            adj[e[1]].append((e[0], e))
        key, _ = ahu_canon(n, adj, {e: 1 for e in edges}, lambda v: 0)
        if key in seen:
            continue
        seen.add(key)
        out.append((edges, n))
    if reporter:
        reporter.emit(rooted_shapes_examined=generated, unique_shapes_generated=len(out))
    return out


def all_trees_upto(nmax):
    out = []
    for n in range(1, nmax + 1):
        out.extend(free_trees(n))
    return out


# ------------------------------------------------------------ GKM graph
def gkm_graph_of_fan(fan, bk):
    """GKM graph with axial weights evaluated in the backend bk.
    Returns (graph, edge_cls, lift) where edge_cls[eid] is the class of
    the wall curve in Z^k and lift[(vertex, ray)] the backend value of the
    restriction of the equivariant divisor class."""
    n = fan.n
    g = GKMGraph(len(fan.max_cones))
    edge_cls = {}
    edge_of = {}
    lift = {}
    for wi, w in enumerate(fan.walls):
        ca, cb = w['cones']
        g.edges.append((ca, cb))
        edge_cls[wi] = w['cls']
        edge_of[(ca, w['tau'])] = wi
        edge_of[(cb, w['tau'])] = wi
    for vi, c in enumerate(fan.max_cones):
        for i in c:
            lift[(vi, i)] = bk.linear([Fraction(x) for x in fan.dual[vi][i]])
        flist = []
        for i in c:
            tau = tuple(j for j in c if j != i)
            eid = edge_of[(vi, tau)]
            b = edge_cls[eid]
            flist.append({'edge': eid, 'ray': i, 'weight': lift[(vi, i)],
                          'a': [b[j] for j in c if j != i], 'cls': b})
        g.flags[vi] = flist
    g.finalize()
    return g, edge_cls, lift


# --------------------------------------------------------------- engine
class ToricGKMEngine(GKMEngine):
    """Genus-0 graph sum with ample-degree pruning of the edge degrees."""

    def __init__(self, fan, bk):
        graph, edge_cls, lift = gkm_graph_of_fan(fan, bk)
        super().__init__(graph, bk)
        self.fan = fan
        self.lift = lift
        self.edge_cls = edge_cls
        amp = fan.ample_divisor()
        self.ample = amp
        self.edge_deg = {eid: fan.wall_degree(amp, cls)
                         for eid, cls in edge_cls.items()}
        assert all(d > 0 for d in self.edge_deg.values())
        self.min_deg = min(self.edge_deg.values())
        self.k = fan.k
        self.cancel = None          # optional callable: True = stop now
        self.progress = None        # optional observational class counters

    def restrict(self, cls):
        """Vector over the fixed points of the restriction of the
        equivariant lift of a CohClass (products of divisor classes)."""
        out = []
        for vi, c in enumerate(self.fan.max_cones):
            cset = set(c)
            tot = 0
            for m, coeff in cls.terms.items():
                if any(i not in cset for i in m):
                    continue
                val = self.bk.rational(coeff)
                for i in m:
                    val = val * self.lift[(vi, i)]
                tot = tot + val
            out.append(tot)
        return out

    def classical(self, insertions):
        """ABBV sum  sum_sigma prod_k gamma_k|_sigma / e_sigma."""
        tot = 0
        for vi in range(self.g.n):
            term = 1
            for ins in insertions:
                term = term * ins[vi]
                if self.bk.is_zero(term):
                    break
            if not self.bk.is_zero(term):
                tot = tot + term / self.g.euler[vi]
        return tot

    # ------------------------------------------------------- graph sum
    def gw(self, insertions, beta):
        return self.gw_multi([tuple(insertions)], beta)[0]

    def gw_multi(self, insertion_sets, beta, twist=None):
        """insertion_sets: list of tuples of insertion vectors, all with
        the same number of marks; beta: class vector in Z^k (must be a
        nonzero element of H_2).  Returns the list of localization sums,
        one per insertion set.  twist: optional ci.LineBundleTwist whose
        vertex/edge factors multiply every fixed locus (quantum
        Lefschetz for a complete intersection)."""
        beta = tuple(beta)
        if not any(beta):
            raise ValueError('use classical() for beta = 0')
        n_marks = {len(s) for s in insertion_sets}
        if len(n_marks) != 1:
            raise ValueError('all insertion sets need the same number of marks')
        n_marks = n_marks.pop()
        total_deg = self.fan.wall_degree(self.ample, beta)
        if total_deg <= 0:
            return [0] * len(insertion_sets)
        max_edges = total_deg // self.min_deg
        acc = [0] * len(insertion_sets)
        reporter = getattr(self, 'progress', None)
        token = ACTIVE_PROGRESS.set(reporter)
        try:
            if reporter:
                reporter.begin_pass(getattr(self, 'evaluation_attempt', 1),
                                    getattr(self, 'evaluation_pass', 1), max_edges)
            trees = all_trees_upto(max_edges + 1)
            if reporter:
                reporter.emit(force=True, stage='localization', trees_total=len(trees))
            for tree_index, (edges, kk) in enumerate(trees, 1):
                if self.cancel is not None and self.cancel():
                    raise Cancelled()
                if reporter:
                    reporter.emit(tree_index=tree_index, tree_vertices=kk,
                                  root_fixed_point=None, root_fixed_points_total=self.g.n)
                self._tree_sum_multi(edges, kk, insertion_sets, n_marks, beta,
                                     total_deg, acc, twist)
                if reporter:
                    reporter.emit(trees_completed=tree_index)
            if reporter:
                reporter.emit(force=True, stage='evaluation_complete')
        finally:
            ACTIVE_PROGRESS.reset(token)
        return acc

    def _tree_sum_multi(self, edges, k, insertion_sets, n_marks, beta,
                        total_deg, acc, twist=None):
        # Forgetting markings sends equivalent marked configurations to the
        # same unmarked decoration. Thus deduplication is local to each group.
        from .decoration_groups import DecorationGroups
        with DecorationGroups(getattr(self, 'decoration_checkpoint', None), len(insertion_sets)) as groups:
            self._tree_sum_grouped(edges, k, insertion_sets, n_marks, beta, total_deg, groups, twist)
            for i, value in enumerate(groups.total):
                acc[i] += value

    def _tree_sum_grouped(self, edges, k, insertion_sets, n_marks, beta,
                          total_deg, groups, twist=None):
        import json
        g = self.g
        bk = self.bk
        adj = {v: [] for v in range(1, k + 1)}
        for e in edges:
            adj[e[0]].append((e[1], e))
            adj[e[1]].append((e[0], e))
        order, seen, bfs = [1], {1}, []
        for v in order:
            for w, e in adj[v]:
                if w not in seen:
                    seen.add(w)
                    bfs.append((w, v, e))
                    order.append(w)
        marks_options = all_possible_marks(n_marks, k)
        vimg = {v: None for v in range(1, k + 1)}
        eimg = {}
        n_edges = len(bfs)
        reporter = getattr(self, 'progress', None)

        def emit():
            if reporter:
                reporter.matching_assignments += 1
            edeg = {e: (eimg[e][0], eimg[e][1]) for e in edges}
            unmarked, _ = ahu_canon(k, adj, edeg, vimg.__getitem__)
            key_unmarked = json.dumps(unmarked, separators=(',', ':'))
            if groups.contains(key_unmarked):
                return
            seen_canon = set()  # At most k**n_marks keys, released after this decoration.
            contribution = [0] * len(insertion_sets)
            for marks in marks_options:
                if reporter:
                    reporter.marked_configurations += 1
                    if reporter.marked_configurations % 1024 == 0:
                        reporter.emit()
                key, aut = ahu_canon(
                    k, adj, edeg, lambda v: (vimg[v], marks[v - 1]))
                if key in seen_canon:
                    continue
                seen_canon.add(key)
                if reporter:
                    reporter.fixed_loci += 1
                base, carriers = self._base(edges, k, adj, vimg, eimg,
                                            marks, aut, twist)
                for s, ins in enumerate(insertion_sets):
                    t = base
                    for m in range(n_marks):
                        t = t * ins[m][carriers[m]]
                        if bk.is_zero(t):
                            break
                    if not bk.is_zero(t):
                        contribution[s] = contribution[s] + t

            groups.add(key_unmarked, contribution)

        def assign(idx, rem_cls, rem_deg):
            if reporter:
                reporter.visit_assignment()
            if idx == n_edges:
                if not any(rem_cls):
                    emit()
                return
            child, parent, e = bfs[idx]
            pv = vimg[parent]
            reserve = (n_edges - idx - 1) * self.min_deg
            for fi, fl in enumerate(g.flags[pv]):
                eid = fl['edge']
                dg = self.edge_deg[eid]
                cls = self.edge_cls[eid]
                dmax = (rem_deg - reserve) // dg
                far = g.edges[eid]
                for d in range(1, dmax + 1):
                    new_cls = tuple(r - d * c for r, c in zip(rem_cls, cls))
                    vimg[child] = far[0] + far[1] - pv
                    eimg[e] = (eid, d, pv, fi)
                    assign(idx + 1, new_cls, rem_deg - d * dg)
            vimg[child] = None
            eimg.pop(e, None)

        for v0 in range(g.n):
            if self.cancel is not None and self.cancel():
                raise Cancelled()
            vimg[1] = v0
            if reporter:
                reporter.emit(root_fixed_point=v0 + 1)
            assign(0, beta, total_deg)

    def _base(self, edges, k, adj, vimg, eimg, marks, aut, twist=None):
        """Class-independent factor of one fixed locus (everything in the
        graph sum except prod_k gamma_k|_{p_{mk(k)}}), and the vertex
        image carrying each mark.  With a twist, the Euler class of the
        bundle of sections of the fixed locus is included."""
        g = self.g
        contrib = self.bk.rational(Fraction(1, aut))
        for e in edges:
            eid, d, pv, fi = eimg[e]
            contrib = contrib * self.h(pv, fi, d) / d
            if twist is not None:
                contrib = contrib * twist.edge(pv, fi, d)
        carriers = {}
        for v in range(1, k + 1):
            fv = vimg[v]
            val = len(adj[v])
            nmk = len(marks[v - 1])
            for m in marks[v - 1]:
                carriers[m - 1] = fv
            contrib = contrib * g.euler[fv] ** (val - 1)
            if twist is not None:
                contrib = contrib * twist.vertex(fv) ** (1 - val)
            s = 0
            for w, e in adj[v]:
                eid, d, pv, fi = eimg[e]
                wt = g.flags[pv][fi]['weight']
                if pv != fv:
                    wt = -wt
                ia = d / wt
                contrib = contrib * ia
                s = s + ia
            expo = nmk + val - 3
            if expo:
                contrib = contrib * s ** expo
        return contrib, carriers
